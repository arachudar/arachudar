def clean_tamil_text(text: str) -> str:
    """Removes Latin/English characters and normalizes whitespace."""
    if not text:
        return ""
    cleaned = re.sub(r"[a-zA-Z]+", "", text)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    return cleaned


